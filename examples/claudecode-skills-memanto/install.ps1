# Installer for Claude Code x Memanto hooks (Windows PowerShell).
#
# - Copies hooks to $env:USERPROFILE\.claude\hooks\memanto\
# - Merges hook config into $env:USERPROFILE\.claude\settings.json
# - Writes .env with MOORCHEH_API_KEY (prompts if missing)
# - Backs up settings.json before mutating it
#
# Run safely multiple times.

$ErrorActionPreference = 'Stop'

$Here       = $PSScriptRoot
$TargetDir  = Join-Path $env:USERPROFILE '.claude\hooks\memanto'
$Settings   = Join-Path $env:USERPROFILE '.claude\settings.json'
$Backup     = "$Settings.bak.$(Get-Date -Format 'yyyyMMdd-HHmmss')"

Write-Host ('Installing Claude Code x Memanto hooks into {0}' -f $TargetDir)

New-Item -ItemType Directory -Force -Path $TargetDir | Out-Null
Copy-Item -Force (Join-Path $Here 'hooks\_memanto_common.py')  $TargetDir
Copy-Item -Force (Join-Path $Here 'hooks\inject_context.py')   $TargetDir
Copy-Item -Force (Join-Path $Here 'hooks\distill_session.py')  $TargetDir
Copy-Item -Force (Join-Path $Here 'hooks\skill_decisions.py')  $TargetDir

# --- .env handling -----------------------------------------------------------
$EnvFile = Join-Path $TargetDir '.env'
if (-not (Test-Path $EnvFile)) {
    $key = $env:MOORCHEH_API_KEY
    if (-not $key) {
        $key = Read-Host 'Paste your Moorcheh API key (from https://console.moorcheh.ai/api-keys)'
    }
    @(
        ('# Auto-generated by install.ps1 on {0}' -f (Get-Date -Format 'u'))
        ('MOORCHEH_API_KEY={0}' -f $key)
    ) | Out-File -FilePath $EnvFile -Encoding utf8
    Write-Host ('Wrote {0}' -f $EnvFile)
} else {
    Write-Host ('{0} already present - left untouched' -f $EnvFile)
}

# --- Settings merge ----------------------------------------------------------
$settingsDir = Split-Path $Settings -Parent
New-Item -ItemType Directory -Force -Path $settingsDir | Out-Null

if (Test-Path $Settings) {
    Copy-Item $Settings $Backup
    Write-Host ('Backed up settings to {0}' -f $Backup)
} else {
    Set-Content $Settings '{}' -Encoding utf8
}

$pythonExe = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $pythonExe) {
    $pythonExe = (Get-Command python3 -ErrorAction SilentlyContinue).Source
}
if (-not $pythonExe) {
    Write-Error 'Python not found on PATH. Install Python 3.10+ and re-run.'
    exit 1
}

$mergeScript = @'
import json
import sys
from pathlib import Path

settings_path = Path(sys.argv[1])
snippet_path  = Path(sys.argv[2])

settings = json.loads(settings_path.read_text(encoding="utf-8") or "{}")
snippet  = json.loads(snippet_path.read_text(encoding="utf-8"))

settings.setdefault("hooks", {})

for event_name, entries in snippet["hooks"].items():
    existing = settings["hooks"].setdefault(event_name, [])
    for entry in entries:
        matcher = entry.get("matcher", "*")
        bucket = next((b for b in existing if b.get("matcher") == matcher), None)
        if bucket is None:
            existing.append(entry); continue
        existing_commands = {
            h.get("command") for h in bucket.get("hooks", []) if isinstance(h, dict)
        }
        for h in entry.get("hooks", []):
            if h.get("command") not in existing_commands:
                bucket.setdefault("hooks", []).append(h)

settings_path.write_text(
    json.dumps(settings, indent=2, ensure_ascii=False) + "\n",
    encoding="utf-8",
)
print(f"Merged hook config into {settings_path}")
'@

$tmp = New-TemporaryFile
Set-Content $tmp.FullName $mergeScript -Encoding utf8
& $pythonExe $tmp.FullName $Settings (Join-Path $Here 'claude-settings.snippet.json')
Remove-Item $tmp.FullName -Force

Write-Host ''
Write-Host 'Installation complete.'
Write-Host ''
Write-Host 'Next steps:'
Write-Host ('  1. Verify with:  python {0}\demo\verify_setup.py' -f $Here)
Write-Host ('  2. Start a Claude Code session and watch {0}\logs\ for hook activity.' -f $TargetDir)
Write-Host '  3. (Optional) For team-shared memory, drop a .claude-memanto.json in any project root:'
Write-Host '       { "agent_id": "team-shared", "extra_tags": ["team:platform"] }'
Write-Host ''
Write-Host ('Uninstall any time:  {0}\uninstall.ps1' -f $Here)
