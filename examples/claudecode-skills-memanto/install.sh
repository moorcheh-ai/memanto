#!/usr/bin/env bash
# Installer for Claude Code × Memanto hooks (macOS / Linux / WSL).
#
# - Copies hooks to ~/.claude/hooks/memanto/
# - Merges hook config into ~/.claude/settings.json (idempotent)
# - Writes ~/.claude/hooks/memanto/.env (prompts for MOORCHEH_API_KEY)
# - Backs up settings.json before mutating it
#
# Re-run safely as many times as you want.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET_DIR="${HOME}/.claude/hooks/memanto"
SETTINGS="${HOME}/.claude/settings.json"
BACKUP="${SETTINGS}.bak.$(date +%Y%m%d-%H%M%S)"

echo "▸ Installing Claude Code × Memanto hooks into ${TARGET_DIR}"

mkdir -p "${TARGET_DIR}"
cp "${HERE}/hooks/_memanto_common.py"     "${TARGET_DIR}/"
cp "${HERE}/hooks/inject_context.py"      "${TARGET_DIR}/"
cp "${HERE}/hooks/distill_session.py"     "${TARGET_DIR}/"
cp "${HERE}/hooks/skill_decisions.py"     "${TARGET_DIR}/"
chmod +x "${TARGET_DIR}"/*.py

# ── .env handling ──────────────────────────────────────────────────────────
ENV_FILE="${TARGET_DIR}/.env"
if [[ ! -f "${ENV_FILE}" ]]; then
    if [[ -z "${MOORCHEH_API_KEY:-}" ]]; then
        echo
        read -r -p "Paste your Moorcheh API key (from https://console.moorcheh.ai/api-keys): " input_key
        MOORCHEH_API_KEY="${input_key}"
    fi
    {
        echo "# Auto-generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo "MOORCHEH_API_KEY=${MOORCHEH_API_KEY}"
    } > "${ENV_FILE}"
    chmod 600 "${ENV_FILE}"
    echo "▸ Wrote ${ENV_FILE} (mode 600)"
else
    echo "▸ ${ENV_FILE} already present — left untouched"
fi

# ── Settings merge ─────────────────────────────────────────────────────────
mkdir -p "$(dirname "${SETTINGS}")"
if [[ -f "${SETTINGS}" ]]; then
    cp "${SETTINGS}" "${BACKUP}"
    echo "▸ Backed up settings to ${BACKUP}"
else
    echo "{}" > "${SETTINGS}"
fi

# Use Python to merge the snippet — jq isn't universally installed
python3 - "${SETTINGS}" "${HERE}/claude-settings.snippet.json" <<'PY'
import json
import sys
from pathlib import Path

settings_path = Path(sys.argv[1])
snippet_path  = Path(sys.argv[2])

settings = json.loads(settings_path.read_text(encoding="utf-8") or "{}")
snippet  = json.loads(snippet_path.read_text(encoding="utf-8"))

settings.setdefault("hooks", {})

for event_name, entries in snippet["hooks"].items():
    existing = settings["hooks"].setdefault(event_name, [])
    for entry in entries:
        matcher = entry.get("matcher", "*")
        # Find or create the bucket for this matcher
        bucket = next(
            (b for b in existing if b.get("matcher") == matcher),
            None,
        )
        if bucket is None:
            existing.append(entry)
            continue
        # Merge hooks, skipping commands already wired
        existing_commands = {
            h.get("command")
            for h in bucket.get("hooks", [])
            if isinstance(h, dict)
        }
        for h in entry.get("hooks", []):
            if h.get("command") not in existing_commands:
                bucket.setdefault("hooks", []).append(h)

settings_path.write_text(
    json.dumps(settings, indent=2, ensure_ascii=False) + "\n",
    encoding="utf-8",
)
print(f"▸ Merged hook config into {settings_path}")
PY

cat <<EOF

✓ Installation complete.

Next steps:
  1. Verify with:   python3 ${HERE}/demo/verify_setup.py
  2. Start a Claude Code session and watch ${TARGET_DIR}/logs/ for hook activity.
  3. (Optional) For team-shared memory, drop a .claude-memanto.json in any project root:
       { "agent_id": "team-shared", "extra_tags": ["team:platform"] }

Uninstall any time:  ${HERE}/uninstall.sh
EOF
